def crumbs(items):
    """items: list of (label, href or None)."""
    lis = []
    for label, href in items:
        lis.append(f'<li><a href="{href}">{e(label)}</a></li>' if href else f'<li><span aria-current="page">{e(label)}</span></li>')
    return '<ol class="crumbs" data-anim="1" aria-label="Okruszki">\n            ' + '\n            '.join(lis) + '\n          </ol>'


def breadcrumb_ld(items):
    return {'@context': 'https://schema.org', '@type': 'BreadcrumbList', 'itemListElement': [
        dict({'@type': 'ListItem', 'position': i + 1, 'name': label}, **({'item': href} if href else {}))
        for i, (label, href) in enumerate(items)]}


def icon(name):
    return f'<svg viewBox="0 0 24 24" aria-hidden="true">{ICONS[name]}</svg>'


def blocks_html(blocks):
    """Content blocks → plain editor markup (what the WordPress block editor outputs)."""
    parts = []
    for b in blocks:
        if isinstance(b, dict):
            parts.append('<ul>\n' + '\n'.join(f'  <li>{t}</li>' for t in b['checks']) + '\n</ul>')
        else:
            parts.append(f'<p>{b}</p>')
    return '\n'.join(parts)


def entry_content(intro, sections, extra=''):
    """The body as it would come from the_content(): intro paragraph + h2 sections."""
    body = [f'<p>{intro}</p>']
    for title, blocks in sections:
        body.append(f'<h2>{title}</h2>')
        body.append(blocks_html(blocks))
    if extra:
        body.append(extra)
    inner = '\n'.join(body).replace('\n', '\n          ')
    return f'<div class="entry-content">\n          {inner}\n        </div>'


