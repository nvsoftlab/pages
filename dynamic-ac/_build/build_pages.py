def entry(intro, sections):
    out = [f'        <p>{intro}</p>']
    for title, paras in sections:
        out.append(f'        <h2>{e(title)}</h2>')
        out += [f'        <p>{p}</p>' for p in paras]
    return '\n'.join(out)


def faq_details(items):
    return '\n'.join(
        f'        <details{" open" if i == 0 else ""}><summary>{e(q)}</summary><p>{a}</p></details>'
        for i, (q, a) in enumerate(items))


