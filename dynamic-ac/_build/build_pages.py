def write(path: Path, content: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding='utf-8')
    print(f'  {path.relative_to(ROOT.parent)}  ({len(content) // 1024} KB)')


def main():
    print('Dynamic AC — building sub-pages')
    for s in SERVICES:
        write(ROOT / s['slug'] / 'index.html', build_service(s))
    write(ROOT / 'kontakt' / 'index.html', build_contact())
    write(ROOT / 'blog' / 'index.html', build_blog_index())
    for p in POSTS:
        write(ROOT / 'blog' / p['slug'] / 'index.html', build_post(p))
    print('done.')


