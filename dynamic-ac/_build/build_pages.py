def crumbs(r, trail):
    """trail: list of (href|None, label); the last item is the current page."""
    out = [f'<a href="{r or "/"}">Strona główna</a>']
    for href, label in trail:
        out.append('<span aria-hidden="true">›</span>')
        out.append(f'<a href="{href}">{e(label)}</a>' if href else f'<span>{e(label)}</span>')
    return '<nav class="crumbs" aria-label="Okruszki">' + ''.join(out) + '</nav>'


