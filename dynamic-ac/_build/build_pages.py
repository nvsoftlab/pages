    for kind, val in blocks:
        if kind == 'h2':
            out.append(f'        <h2>{e(val)}</h2>')
        elif kind == 'p':
            out.append(f'        <p>{val}</p>')
        elif kind == 'ul':
            lis = ''.join(f'<li>{e(x)}</li>' for x in val)
            out.append(f'        <ul>{lis}</ul>')
        elif kind == 'ol':
            lis = ''.join(f'<li>{e(x)}</li>' for x in val)
            out.append(f'        <ol>{lis}</ol>')
        elif kind == 'callout':
            paras = ''.join(f'<p>{e(x)}</p>' for x in val)
            out.append(f'        <div class="callout">{paras}</div>')
    return '\n'.join(out)


