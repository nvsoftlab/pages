def build_service(s):
    r = '../'
    ld_service = {
        '@context': 'https://schema.org', '@type': 'Service',
        'name': s['name'], 'serviceType': s['name'], 'description': s['desc'],
        'areaServed': {'@type': 'City', 'name': 'Wrocław'},
        'provider': dict(BUSINESS, **{'@context': 'https://schema.org'}),
        'url': f'{SITE}/{s["slug"]}/',
    }
    ld_faq = {
        '@context': 'https://schema.org', '@type': 'FAQPage',
        'mainEntity': [{'@type': 'Question', 'name': q,
                        'acceptedAnswer': {'@type': 'Answer', 'text': html.unescape(
                            __import__('re').sub('<[^>]+>', '', a))}}
                       for q, a in s['faq']],
    }
    ld_crumbs = {
        '@context': 'https://schema.org', '@type': 'BreadcrumbList',
        'itemListElement': [
            {'@type': 'ListItem', 'position': 1, 'name': 'Strona główna', 'item': SITE + '/'},
            {'@type': 'ListItem', 'position': 2, 'name': 'Usługi', 'item': SITE + '/#uslugi'},
            {'@type': 'ListItem', 'position': 3, 'name': s['name'], 'item': f'{SITE}/{s["slug"]}/'},
        ],
    }

    alts = [f'{s["name"]} — mobilny serwis Dynamic AC we Wrocławiu ({i})' for i in (1, 2, 3)]

    html_out = head(r, s['title'], s['desc'], f'{SITE}/assets/img/{s["hero_img"]}',
                    [ld_service, ld_faq, ld_crumbs],
                    preload=f'{r}assets/img/{s["hero_img"]}', canonical=f'{s["slug"]}/')
    html_out += topbar()
    html_out += header(r, 'uslugi')
    html_out += '\n<main id="main">\n'
    html_out += phero(r, s['pill'], s['h1'], e(s['lead']), s['hero_img'],
                      [(r + '#uslugi', 'Usługi'), (None, s['name'])], s['highlights'])

    html_out += f'''
  <section class="section">
    <div class="container">
      <div class="article">
        <div class="entry-content">
{entry(s['intro'], s['sections'])}
        <h2>Najczęstsze pytania</h2>
{faq_details(s['faq'])}
        </div>

        <aside>
          <div class="toc">
            <div class="toc__title">Na tej stronie</div>
            <nav data-toc aria-label="Spis treści"></nav>
          </div>
          <div class="aside-cta">
            <b>Umów {e(s['cta'])}</b>
            <p>Przyjeżdżamy pod dom, biuro albo na parking. Dojazd w obrębie Wrocławia w cenie usługi.</p>
            <a class="btn btn--primary btn--sm" href="{TEL}">Zadzwoń: {PHONE}</a>
            <a class="btn btn--outline btn--sm" href="#kontakt">Zostaw kontakt</a>
          </div>
        </aside>
      </div>
    </div>
  </section>
'''
    html_out += steps_block(s['steps_title'], s['steps_lead'], s['steps'])
    html_out += gallery_block(r, s['gallery'], alts)
    html_out += xlinks_block(r, s['slug'])
    html_out += cta_section(r, s['name'])
    html_out += '\n</main>\n'
    html_out += footer(r)
    html_out += floats(r, lightbox=True)
    return html_out


