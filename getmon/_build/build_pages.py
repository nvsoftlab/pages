def header(r, active_group=None, active_slug=None):
    """active_group: nav group key, or 'blog'. active_slug: current service slug."""
    items = []
    for key, label, hub, children in NAV_GROUPS:
        on = ' is-active' if key == active_group else ''
        if not children:
            items.append(f'        <a href="{r}{hub}/" class="nav__link{on}">{label}</a>')
            continue
        links = '\n'.join(
            '          <a href="%s%s/"%s>%s</a>'
            % (r, c, ' class="is-active"' if c == active_slug else '', SHORT[c])
            for c in children)
        items.append(f'''        <div class="nav__item">
          <a href="{r}{hub}/" class="nav__link{on}">{label}{CARET}</a>
          <div class="nav__menu">
{links}
          </div>
        </div>''')
    items.append(f'        <a href="{r}blog/" class="nav__link'
                 f'{" is-active" if active_group == "blog" else ""}">Blog</a>')
