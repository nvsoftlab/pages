MARKS = [('TOPBAR', lambda: topbar()),
         ('HEROFORM', lambda: quote_card('hero', '', None, r='')),
         ('HEADER', lambda: header('', None, None)),
         ('BAND', lambda: band('', 'Darmowa wycena, zero zobowiązań',
                               'Opisz obiekt i zakres prac — odezwiemy się z konkretną propozycją.')),
         ('CONTACT', lambda: contact('')),
         ('FOOTER', lambda: footer(''))]


def sync_home():
    """index.html keeps <!--#X--> ... <!--/#X--> markers; refill them from here."""
    f = ROOT / 'index.html'
    if not f.exists():
        return
    s = f.read_text(encoding='utf-8')
    for name, fn in MARKS:
        pat = re.compile(f'(<!--#{name}-->)(.*?)(<!--/#{name}-->)', re.S)
        if not pat.search(s):
            print(f'  ! index.html: missing marker {name}')
            continue
        s = pat.sub(lambda m: m.group(1) + fn() + '  ' + m.group(3), s)
    # hero + in-page forms live in index.html itself; only chrome is synced.
    f.write_text(s, encoding='utf-8')
    print('  index.html (chrome synced)')


def write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding='utf-8')
    print(f'  {path.relative_to(ROOT)}')


