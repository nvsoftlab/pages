def render_blocks(blocks, r):
    out = []
    for b in blocks:
        if 'callout' in b:
            title, body = b['callout']
            out.append(f'        <div class="callout" data-reveal><p>{e(title)}</p><p>{e(body)}</p></div>')
            continue
        if b.get('h2'):
            out.append(f'        <h2 data-reveal>{e(b["h2"])}</h2>')
        for p in b.get('p', []):
            out.append(f'        <p data-reveal>{e(p)}</p>')
        if b.get('ul'):
            lis = '\n'.join(f'          <li>{e(x)}</li>' for x in b['ul'])
            out.append(f'        <ul data-reveal>\n{lis}\n        </ul>')
        for h3, ps in b.get('h3', []):
            out.append(f'        <h3 data-reveal>{e(h3)}</h3>')
            for p in ps:
                out.append(f'        <p data-reveal>{e(p)}</p>')
        if b.get('img'):
            cap = f'\n          <figcaption>{e(b["cap"])}</figcaption>' if b.get('cap') else ''
            out.append(f'''        <figure data-reveal>
          <img src="{r}assets/img/bg/{b["img"]}.jpg" alt="{e(b.get("cap", ""))}" loading="lazy" width="1800" height="1200">{cap}
        </figure>''')
    return '\n'.join(out)


