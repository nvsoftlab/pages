def chips(active_label=None):
    out = []
    for i, c in enumerate(CHIPS):
        on = (c == active_label) if active_label else (i == 0)
        out.append(f'<button type="button" class="chip{" is-active" if on else ""}" role="radio" '
                   f'aria-checked="{"true" if on else "false"}">{c}</button>')
    return '\n                    '.join(out)


