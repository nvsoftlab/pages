def drawer_nav(r):
    out = []
    for key, label, hub, children in NAV_GROUPS:
        if not children:
            out.append(f'        <a href="{r}{hub}/" data-close>{label}</a>')
            continue
        out.append(f'        <span class="drawer__group">{label}</span>')
        for c in children:
            out.append(f'        <a href="{r}{c}/" class="is-sub" data-close>{SHORT[c]}</a>')
